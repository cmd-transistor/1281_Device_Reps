SELECT
  TESTROW.CADENCELIBRARY,
  TESTROW.TESTROWNAME,
  TESTSTRUCTURE.TESTSTRUCTNAME,
  TESTSTRUCTURE.TESTSTRUCTCOMMENT,
  STRUCTURETEMPLATE.TEMPLATENAME,
  STRUCTURETEMPLATE.CATEGORY,
  TESTSTRUCTUREPARAMETERS.PARAMETERNAME,
  TESTSTRUCTUREPARAMETERS.PARAMETERVALUE,
  TESTSTRUCTURE.TESTSTRUCTID,
  CONTAINERCELLROWSTRUCTURES.CADENCESTRUCTNAME
FROM
  TESTROW,
  TESTSTRUCTURE,
  STRUCTURETEMPLATE,
  TESTSTRUCTUREPARAMETERS,
  TESTROWHOOKUP,
  CONTAINERCELLROWSTRUCTURES
WHERE
  TESTROW.TESTROWID=TESTSTRUCTURE.TESTROWID(+) 
  AND TESTROW.TESTROWID=TESTROWHOOKUP.TESTROWID(+) 
  AND  TESTSTRUCTURE.TESTSTRUCTID=TESTSTRUCTUREPARAMETERS.TESTSTRUCTID(+)
  AND TESTSTRUCTURE.TESTSTRUCTID=TESTROWHOOKUP.TESTSTRUCTUREID(+)
  AND  TESTSTRUCTURE.TSTEMPLATEID=STRUCTURETEMPLATE.TEMPLATEID
  AND TESTROW.TESTROWNAME=CONTAINERCELLROWSTRUCTURES.ROWNAME(+)
  AND TESTSTRUCTURE.TESTSTRUCTNAME=CONTAINERCELLROWSTRUCTURES.STRUCTURENAME(+)
  AND  TESTROW.LATESTFLAG='1' 
  AND STRUCTURETEMPLATE.TEMPLATENAME NOT LIKE '%GNAC%'
  AND TESTROW.TESTROWNAME IN ('x80bs_llec1n07','x80bs_llec1p07','x80bs_mncl15','x80bs_mpcl15','x80bs_ncl02','x80bs_pcl02','x80bs_rospft12','x80bs_rospft13','x80bs_rospft14')
  AND TESTSTRUCTUREPARAMETERS.PARAMETERNAME IN ('zone','Scalar','Type','MOSVT Type','KLV', 'LEGS_SHARED', 'LEGS_STACKED', 'GANG', 'INSTANCES', 'LGATE', 'LNR_PDK', 'RIBBONS_PDK', 'TSI_PDK')
  AND TESTSTRUCTUREPARAMETERS.PARAMETERVALUE is not null